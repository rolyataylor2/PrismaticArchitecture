import test from 'node:test';
import assert from 'node:assert/strict';
import { existsSync } from 'node:fs';
import { once } from 'node:events';
import type { AddressInfo } from 'node:net';
import { chromium } from '@playwright/test';
import { SqliteStore } from '../../packages/storage/src/sqlite.js';
import { Application } from './persistent-fixture.js';
import { createResearchServer } from '../../apps/server/src/server.js';
import type { Prediction } from '../../packages/core/src/domain.js';

const executable = process.env.CHROME_BIN ?? '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome';
test('Part inspector selects history and opens styled and raw information', { skip: !existsSync(executable) }, async () => {
  const store = new SqliteStore(':memory:'); const app = new Application(store);
  const agent = app.createAgent('Part inspector'); const original = store.list('part', agent.id)[0]!;
  store.save('disposition', { id: 'inspector_disposition', agentId: agent.id, version: 1, schemaVersion: 1,
    name: 'Being Heard', concern: 'Notice opportunities to be understood.', cues: ['Someone listens'], scope: 'Conversation',
    prerequisites: [], threshold: 2, memoryIds: [], sourcePredictionId: null, temporary: false, active: true }, 0,
    { origin: 'researcher_edit', reason: 'Explicit source binding for inspector verification', sourceIds: [] });
  store.save('disposition', { ...store.get('disposition', 'inspector_disposition'), version: 2,
    concern: 'Notice current opportunities to be understood.' }, 1,
    { origin: 'researcher_edit', reason: 'Updated concern for version navigation', sourceIds: [] });
  const formationCycle = store.startCycle(agent.id); store.saveCycle({ ...formationCycle, status: 'completed' });
  app.runtime.mutations.patch(original.id, original.version, { instance: { createdCycle: formationCycle.id, threadId: null,
    interpretation: 'I want to be understood.', evidenceMemoryIds: [], counterevidenceMemoryIds: [],
    dispositionBindings: [{ dispositionId: 'inspector_disposition', entityId: 'conversation' }], retirement: null }, mission: 'My newer mission', beliefs: ['I deserve to be heard.'], emotionalCharge: 'Tentative trust', temporary: true }, { origin: 'researcher_edit', reason: 'Inspector fixture', sourceIds: [] });
  const capsule = { interpretation: 'I expect a response.', details: ['I asked a question.'], entities: ['Someone'], activation: 2, spike: 1, sourceIds: [] };
  const change = { origin: 'researcher_edit' as const, reason: 'Inspector fixture', sourceIds: [] };
  for (const [index, assessment] of ['confirmed', 'contradicted', 'ambiguous', null].entries()) {
    const prediction: Prediction = { id: `inspector_prediction_${index}`, agentId: agent.id, partId: original.id, version: 1, schemaVersion: 1,
      expectation: `Expectation ${index}`, capsule, confidence: .712345, horizon: 'Next response', evaluateAfterCycle: null, createdCycle: 'fixture_cycle',
      status: assessment ? 'resolved' : 'open', memoryId: null, evaluation: assessment ? { assessment: assessment as 'confirmed' | 'contradicted' | 'ambiguous', interpretation: 'My interpretation of the result.', causalAttribution: 'Their response mattered.', evidence: ['They replied.'], evidenceWorldId: 'fixture_world' } : null };
    store.save('prediction', index === 0 ? { ...prediction, expectation: 'Earlier expectation', status: 'open', evaluation: null } : prediction, 0, change);
    if (index === 0) store.save('prediction', { ...prediction, version: 2 }, 1, { ...change, reason: 'Resolved with later evidence', sourceIds: ['later_evidence'] });
  }
  const sourceCycle = store.startCycle(agent.id);
  store.saveWorld({ id: sourceCycle.worldId, agentId: agent.id, cycleId: sourceCycle.id, sequence: sourceCycle.sequence, capturedAt: sourceCycle.startedAt, facts: [{ source: 'Someone', kind: 'says', text: 'I am listening.', timestamp: sourceCycle.startedAt, referenceId: null }] });
  store.saveCycle({ ...sourceCycle, status: 'completed' });
  store.save('memory', { id: 'inspector_memory', agentId: agent.id, partId: original.id, version: 1, schemaVersion: 1, gist: 'I felt heard.', content: 'They listened carefully to me.', context: ['A conversation'], ancestorIds: [sourceCycle.worldId], predictionId: null, createdCycle: sourceCycle.id }, 0, change);
  store.save('memory', { ...store.get('memory', 'inspector_memory'), version: 2, content: 'They listened carefully to me. I can reconsider what this meant.' }, 1, { ...change, reason: 'Reinterpreted my memory' });
  for (let index = 0; index < 7; index++) app.inspection.emit(agent.id, null, 'part.thought', {
    partId: original.id, partSnapshot: store.get('part', original.id), predictionSnapshot: null,
    output: { interpretation: 'My perspective', thought: `Recorded thought ${index}`, evidenceSummary: ['My evidence'], proposal: null }, durationMs: 12,
  });
  const server = createResearchServer(app); server.listen(0, '127.0.0.1'); await once(server, 'listening');
  const browser = await chromium.launch({ executablePath: executable, headless: true });
  try {
    const page = await browser.newPage(); const errors: string[] = []; page.on('pageerror', cause => errors.push(cause.message));
    await page.goto(`http://127.0.0.1:${(server.address() as AddressInfo).port}`);
    await page.getByRole('button', { name: 'Memories', exact: true }).waitFor();
    assert.equal(await page.getByRole('button', { name: 'Memories', exact: true }).count(), 1);
    await page.getByRole('button', { name: 'Part History', exact: true }).click();
    const card = page.getByRole('button', { name: `Inspect ${original.name}`, exact: true });
    assert.equal(await page.locator('.part-list-inspect').count(), 0);
    assert.equal(await card.evaluate(element => getComputedStyle(element).borderTopStyle), 'dashed');
    assert.match(await card.locator('.part-list-thought').innerText(), /Expectation 3/);
    assert.equal(await page.locator('.parts-list').evaluate(element => getComputedStyle(element).gridTemplateColumns.split(' ').length), 4);
    const archivedPart = store.list('part', agent.id)[1]!;
    app.runtime.mutations.patch(archivedPart.id, archivedPart.version, { lifecycle: 'archived', emotionalCharge: 'Tentative trust' }, change);
    await page.reload();
    await page.getByRole('button', { name: 'Part History', exact: true }).click();
    assert.equal(await page.getByRole('button', { name: `Inspect ${archivedPart.name}`, exact: true }).evaluate(element => getComputedStyle(element).backgroundColor), 'rgb(236, 238, 237)');
    await card.click();
    await page.getByRole('navigation', { name: 'Part version timeline' }).waitFor();
    assert.equal(await page.getByRole('button', { name: 'Back to Parts', exact: true }).count(), 0);
    assert.equal(await page.getByRole('heading', { name: 'Perspective History', exact: true }).count(), 1);
    assert.equal(await page.locator('.part-inspector-name').getByRole('button', { name: 'Edit perspective', exact: true }).count(), 1);
    await page.evaluate(() => window.scrollTo(0, 600));
    assert.ok((await page.locator('aside').boundingBox())!.y >= 0);
    assert.ok((await page.locator('.part-version-timeline').boundingBox())!.y >= 0);
    await page.evaluate(() => window.scrollTo(0, 0));
    assert.equal(await page.locator('#content pre').count(), 0);
    assert.match(await page.locator('.part-description').innerText(), /My newer mission/);
    assert.match(await page.locator('.part-description').innerText(), /Retrieval keys · vector search only/);
    for (const key of original.retrievalKeys ?? []) assert.ok((await page.locator('.part-description').innerText()).includes(key));
    assert.equal(await page.locator('.part-beliefs li').innerText(), '✓\nI deserve to be heard.');
    const disposition = page.getByRole('button', { name: 'Inspect disposition: Being Heard', exact: true });
    await disposition.click();
    const dispositionPanel = page.getByRole('region', { name: 'Disposition inspector', exact: true });
    await dispositionPanel.getByRole('heading', { name: 'Being Heard', exact: true, level: 2 }).waitFor();
    assert.match(await dispositionPanel.innerText(), /Notice current opportunities to be understood/);
    const previousDisposition = dispositionPanel.getByRole('button', { name: 'Previous disposition version', exact: true });
    const nextDisposition = dispositionPanel.getByRole('button', { name: 'Next disposition version', exact: true });
    assert.equal(await nextDisposition.isDisabled(), true);
    await previousDisposition.click();
    assert.match(await dispositionPanel.innerText(), /Notice opportunities to be understood/);
    assert.doesNotMatch(await dispositionPanel.innerText(), /Notice current opportunities/);
    assert.match(await dispositionPanel.innerText(), /Disposition v1 · Historical/);
    assert.equal(await previousDisposition.isDisabled(), true);
    await nextDisposition.click();
    assert.match(await dispositionPanel.innerText(), /Disposition v2 · Current/);
    assert.match(await dispositionPanel.innerText(), /Notice current opportunities/);
    assert.match(await dispositionPanel.innerText(), /No recorded activation assessments/);
    assert.equal(await disposition.getAttribute('aria-pressed'), 'true');
    assert.equal(await page.getByRole('button', { name: 'Current version 2', exact: true }).getAttribute('aria-pressed'), 'false');
    assert.equal(await dispositionPanel.getByRole('button', { name: 'Edit disposition', exact: true }).count(), 0);
    await page.screenshot({ path: '/tmp/prism-part-disposition-desktop.png', fullPage: true });
    await page.setViewportSize({ width: 390, height: 844 });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), true);
    await page.screenshot({ path: '/tmp/prism-part-disposition-mobile.png', fullPage: true });
    await page.setViewportSize({ width: 1280, height: 720 });
    await page.getByRole('button', { name: 'Historical version 1', exact: true }).click();
    assert.equal(await disposition.getAttribute('aria-pressed'), 'false');
    assert.equal(await dispositionPanel.count(), 0);
    assert.match(await page.locator('.part-description').innerText(), new RegExp(original.mission.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')));
    assert.equal(await page.getByRole('button', { name: 'Historical version 1', exact: true }).getAttribute('aria-pressed'), 'true');
    assert.equal(await page.locator('.part-record-container:visible').count(), 0);
    assert.equal(await page.getByRole('button', { name: 'Edit perspective', exact: true }).count(), 0);
    const starColor = (version: string) => page.getByRole('button', { name: version, exact: true }).locator('.part-star-symbol').evaluate(icon => getComputedStyle(icon).color);
    assert.notEqual(await starColor('Historical version 1'), await starColor('Current version 2'));
    await page.getByRole('button', { name: 'Raw Part inspector data', exact: true }).click();
    const historicalRaw = page.getByRole('dialog', { name: 'Raw Part inspector data', exact: true });
    await historicalRaw.waitFor(); assert.equal(await historicalRaw.locator('details').count(), 2);
    assert.equal(await historicalRaw.getByText('Subjective memories', { exact: true }).count(), 0);
    await page.keyboard.press('Escape');
    await page.getByRole('button', { name: 'Current version 2', exact: true }).click();
    assert.equal(await page.locator('.part-record-container:visible').count(), 3);
    assert.equal(await starColor('Historical version 1'), 'rgb(169, 182, 166)');
    assert.equal(await starColor('Current version 2'), 'rgb(183, 140, 53)');
    const thoughtSection = page.locator('.part-last-thoughts');
    assert.equal(await thoughtSection.locator('.part-thought-row').count(), 5);
    assert.match(await thoughtSection.locator('.part-thought-row').first().innerText(), /Recorded thought 6/);
    assert.equal(await page.locator('.part-feeling').innerText(), 'I am feeling Tentative trust');
    assert.equal(await page.locator('.part-description').evaluate(element => {
      const feeling = element.querySelector('.part-feeling')!;
      const caption = feeling.nextElementSibling!;
      return caption.classList.contains('part-version-caption') && getComputedStyle(feeling).fontSize === getComputedStyle(caption).fontSize && getComputedStyle(feeling).color === getComputedStyle(caption).color;
    }), true);
    assert.deepEqual(await page.locator('.part-inspector-main > .part-record-container > h3').allTextContents(), ['My predictions', 'Last Thoughts', 'My memories']);
    await thoughtSection.getByRole('button', { name: 'View complete history', exact: true }).click();
    const completeHistory = page.getByRole('dialog', { name: 'Complete thought history', exact: true });
    await completeHistory.waitFor(); assert.equal(await completeHistory.locator('.part-thought-row').count(), 7);
    await completeHistory.getByRole('button', { name: 'Thought information: Recorded thought 0', exact: true }).click();
    const rawThought = page.getByRole('dialog', { name: 'Raw thought object', exact: true });
    await rawThought.waitFor(); assert.match(await rawThought.locator('pre').first().innerText(), /"thought": "Recorded thought 0"/);
    await rawThought.getByRole('button', { name: 'Close information', exact: true }).click();
    assert.equal(await completeHistory.isVisible(), true);
    await page.keyboard.press('Escape');
    await thoughtSection.getByRole('button', { name: 'Thought information: Recorded thought 6', exact: true }).click();
    await rawThought.waitFor(); await page.keyboard.press('Escape');
    for (const kind of ['correct', 'incorrect', 'inconclusive', 'open']) assert.equal(await page.locator(`.prediction-marker.${kind}`).count(), 1);
    assert.match(await page.getByLabel('Current active prediction').innerText(), /Expectation 3/);
    await page.getByRole('button', { name: 'Prediction information: Expectation 0', exact: true }).click();
    const prediction = page.getByRole('dialog', { name: 'Prediction information', exact: true });
    await prediction.waitFor(); assert.match(await prediction.innerText(), /Their response mattered/);
    assert.equal(await prediction.locator('pre').count(), 0);
    assert.equal(await prediction.locator('.prediction-version-list > details').count(), 2);
    assert.equal(await prediction.locator('.prediction-version-list > details[open]').count(), 1);
    assert.match(await prediction.innerText(), /Confidence: 0.712345/);
    assert.match(await prediction.innerText(), /Activation spike: 1/);
    assert.match(await prediction.innerText(), /Activation: 2/);
    assert.match(await prediction.innerText(), /Schema version: 1/);
    assert.match(await prediction.innerText(), /Resolved with later evidence/);
    assert.match(await prediction.innerText(), /later_evidence/);
    await prediction.getByRole('button', { name: 'Inspect raw prediction version', exact: true }).click();
    const rawPrediction = page.getByRole('dialog', { name: 'Raw prediction version', exact: true });
    await rawPrediction.waitFor(); assert.match(await rawPrediction.locator('pre').innerText(), /"confidence": 0.712345/);
    await page.keyboard.press('Escape');
    const priorPrediction = prediction.locator('.prediction-version-list > details').last();
    await priorPrediction.locator('summary').click();
    assert.equal(await prediction.locator('.prediction-version-list > details[open]').count(), 1);
    assert.match(await priorPrediction.innerText(), /Earlier expectation/);
    assert.match(await priorPrediction.innerText(), /Status: open/);
    assert.doesNotMatch(await priorPrediction.innerText(), /Their response mattered/);
    await page.keyboard.press('Escape');
    await page.getByRole('button', { name: 'Memory information: I felt heard.', exact: true }).click();
    const memory = page.getByRole('dialog', { name: 'Memory information', exact: true });
    await memory.waitFor(); assert.match(await memory.innerText(), /They listened carefully/);
    assert.equal(await memory.locator('.memory-version-list > details').count(), 2);
    assert.equal(await memory.locator('.memory-version-list > details[open]').count(), 1);
    assert.match(await memory.locator('.memory-version-list > details[open] summary').innerText(), /Version 2/);
    assert.equal(await memory.getByRole('button', { name: 'View version history', exact: true }).count(), 0);
    const oldMemory = memory.locator('.memory-version-list > details').last(); await oldMemory.locator('summary').click();
    assert.equal(await memory.locator('.memory-version-list > details[open]').count(), 1);
    assert.match(await oldMemory.innerText(), /They listened carefully to me/);
    assert.doesNotMatch(await oldMemory.innerText(), /I can reconsider/);
    await memory.getByRole('heading', { name: 'Originating events · provenance · version 1', exact: true }).waitFor();
    assert.equal(await memory.locator('.modal-body > :last-child').getAttribute('class'), 'memory-provenance');
    await memory.getByRole('button', { name: 'Inspect originating event', exact: true }).click();
    const source = page.getByRole('dialog', { name: 'Originating event · objective audit record', exact: true });
    await source.waitFor(); assert.match(await source.innerText(), /I am listening/);
    await source.getByRole('button', { name: 'Close information', exact: true }).click();
    assert.equal(await memory.isVisible(), true);
    await memory.locator('.memory-version-list > details').first().locator('summary').click();
    assert.equal(await memory.locator('.memory-version-list > details[open]').count(), 1);
    await memory.getByRole('heading', { name: 'Originating events · provenance · version 2', exact: true }).waitFor();
    await memory.getByRole('button', { name: 'Close information', exact: true }).click();
    await page.getByRole('button', { name: 'Raw Part inspector data', exact: true }).click();
    const raw = page.getByRole('dialog', { name: 'Raw Part inspector data', exact: true });
    await raw.waitFor(); assert.equal(await raw.locator('details').count(), 4); assert.match(await raw.innerText(), /My newer mission/);
    await page.keyboard.press('Escape'); assert.equal(await page.locator('#content pre').count(), 0);
    await page.setViewportSize({ width: 390, height: 844 });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), true);
    await page.getByRole('button', { name: 'Dispositions', exact: true }).click();
    await page.getByRole('button', { name: 'Inspect Being Heard', exact: true }).click();
    await dispositionPanel.getByRole('heading', { name: 'Being Heard', exact: true, level: 2 }).waitFor();
    assert.equal(await disposition.getAttribute('aria-pressed'), 'true');
    assert.match(await dispositionPanel.innerText(), /Disposition v2 · Current/);
    await page.getByRole('button', { name: 'Current version 2', exact: true }).click();
    assert.match(await page.locator('.part-description').innerText(), /My newer mission/);
    await page.screenshot({ path: '/tmp/prism-disposition-linked-part-mobile.png', fullPage: true });
    assert.deepEqual(errors, []);
  } finally { await browser.close(); await new Promise<void>(resolve => server.close(() => resolve())); store.close(); }
});
